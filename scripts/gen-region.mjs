const byCode = new Map(
  REGIONS.map(([code, name, sido]) => [code, { code, name, sido, neighbors: new Set() }]),
)
for (const [a, b] of EDGES) {
  if (!byCode.has(a)) throw new Error(`unknown region code in edge: ${a}`)
  if (!byCode.has(b)) throw new Error(`unknown region code in edge: ${b}`)
  if (a === b) throw new Error(`self edge: ${a}`)
  byCode.get(a).neighbors.add(b)
  byCode.get(b).neighbors.add(a)
}

const out = {
  $comment:
    '수도권 66개 시군구 인접 관계. scripts/gen-region.mjs 로 생성한다 — 이 파일을 손으로 수정하지 말 것. 확장 단계에 "같은 시도"를 넣지 않는다 (PRD 확정 결정 9).',
  generatedBy: 'scripts/gen-region.mjs',
  regions: REGIONS.map(([code]) => {
    const r = byCode.get(code)
    return {
      code: r.code,
      name: r.name,
      sido: r.sido,
      label: `${r.sido.replace(/(특별시|광역시|도)$/, '')} ${r.name}`,
      neighbors: [...r.neighbors].sort(),
    }
  }),
}

