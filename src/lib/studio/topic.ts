/**
 * 주제 문자열 다듬기.
 *
 * **캐릭터·상표 이름을 치환하던 규칙을 걷어냈다** (ADR-043).
 *
 * 걷어낸 이유: 이 플랫폼이 무엇이 저작권 침해인지 **판정하지 않는다.** 강사가 "피카츄" 를
 * 넣으면 그 단어로 만든다. 판정하려 들면 세 가지가 동시에 틀린다 —
 *
 *   ① 목록이 영원히 불완전하다. 교실에서 나오는 이름은 계속 생기고, 목록에 없는 이름은
 *      그대로 통과하므로 "막았다" 는 느낌만 주고 실제로 막지 못한다.
 *   ② 멀쩡한 입력을 망친다. "키티" 규칙이 "헬로키티" 를 잡으려다 "키티 캣 그리기" 도 잡았다.
 *      강사는 고양이를 요청했는데 왜 문구가 뜨는지 알 수 없었다.
 *   ③ **판정의 주체가 잘못됐다.** 교실에서 무엇을 쓸지는 강사와 학교가 정한다. 생성 도구가
 *      대신 정하면 강사는 도구를 신뢰하지 않고, 신뢰하지 않는 도구는 두 번 쓰이지 않는다.
 *
 * **화면에 아무 표시도 하지 않는다.** 치환도 거절도 경고 팝업도 책임 고지도 없다 — 판정을
 * 0 으로 내리는 것이 이 결정이고, "당신의 책임입니다" 라는 한 줄도 판정의 흔적이다.
 *
 * 이것이 무책임하지 않은 이유: 스튜디오 산출물을 열람하는 주체는 작성 강사·발주 기관
 * 구성원·운영자 셋뿐이고(ADR-031) 학생·보호자·타 강사·anon 에게 도달하는 경로가 **하나도
 * 없다.** 공개 배포가 구조적으로 불가능한 산출물이라 플랫폼이 배포자가 되지 않는다.
 *
 * 남은 일은 공백 정리뿐이다. 주제 문자열을 **내용으로** 판단하는 코드를 이 파일에 다시
 * 넣지 말 것.
 */

export type GeneralizedTopic = {
  text: string
  /** 호환을 위해 남긴다. **항상 false** — 더 이상 치환하지 않는다 */
  replaced: boolean
  /** 호환을 위해 남긴다. **항상 null** */
  note: string | null
}

/**
 * 공백만 정리한다. 이름은 역사적 이유로 남아 있다 — 호출부가 셋이고, 한 번에 바꾸면
 * 이 변경의 의도("판정하지 않는다")가 리네임 디프에 묻힌다.
 */
export function generalizeCharacter(topic: string): GeneralizedTopic {
  const text = topic.replace(/\s+/g, ' ').trim()
  return { text: text === '' ? topic : text, replaced: false, note: null }
}
